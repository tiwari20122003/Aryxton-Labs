import { useState } from "react";
import { useNavigate } from "react-router-dom";
import { toast } from "sonner";
import { analyzeDomain } from "@/lib/api";
import TopNav from "@/components/TopNav";

const FEATURES = [
  { icon: "fa-solid fa-magnifying-glass-chart", title: "SEO Health", tint: "chip-mint", desc: "Titles, meta, H1, canonical, OG, schema and more — audited for every crawled page." },
  { icon: "fa-solid fa-shield-halved", title: "Security Grade", tint: "chip-lav", desc: "SSL, TLS, OWASP headers, phishing heuristics & malware signatures. A+ to F." },
  { icon: "fa-solid fa-gauge-high", title: "Performance", tint: "chip-peach", desc: "Load time, page weight, LCP estimation and speed scoring across your site." },
  { icon: "fa-solid fa-globe", title: "WHOIS & DNS", tint: "chip-rose", desc: "Registrar, nameservers, MX, A records, robots.txt and sitemap verification." },
  { icon: "fa-solid fa-brain", title: "AI Insights", tint: "chip-lav", desc: "Prioritised action plan generated by the Apodex model via OpenRouter." },
  { icon: "fa-solid fa-file-excel", title: "Excel Export", tint: "chip-mint", desc: "One-click multi-sheet workbook: Overview, Pages, Issues, Audit, Security." },
];

const DOMAIN_RE = /^(https?:\/\/)?([a-zA-Z0-9][-a-zA-Z0-9]{0,61}[a-zA-Z0-9]?\.)+[a-zA-Z]{2,63}(:\d+)?(\/[^\s]*)?$/;

export default function Landing() {
  const nav = useNavigate();
  const [domain, setDomain] = useState("");
  const [pages, setPages] = useState(8);
  const [loading, setLoading] = useState(false);
  const [fieldError, setFieldError] = useState("");
  const [analyzeAbort, setAnalyzeAbort] = useState(null);

  function validateDomain(value) {
    const v = value.trim();
    if (!v) { setFieldError(""); return null; }
    if (!DOMAIN_RE.test(v)) {
      setFieldError("Please enter a valid domain (e.g. example.com)");
      return false;
    }
    setFieldError("");
    return true;
  }

  async function onAnalyze(e) {
    e?.preventDefault?.();
    const d = domain.trim();
    if (!d) {
      setFieldError("Please enter a domain to begin");
      toast.error("Please enter a domain");
      return;
    }
    if (validateDomain(d) === false) {
      toast.error("Invalid domain format");
      return;
    }
    if (analyzeAbort) analyzeAbort.abort();
    const ctrl = new AbortController();
    setAnalyzeAbort(ctrl);
    setLoading(true);
    const messages = [
      `Resolving ${d}…`,
      `Crawling pages · depth ${pages}…`,
      `Checking TLS & headers…`,
      `Compiling report…`,
    ];
    let step = 0;
    const stageTimer = setInterval(() => {
      step = (step + 1) % messages.length;
      toast.message(messages[step], { id: "scan-progress", duration: 10000 });
    }, 2200);
    const t = toast.loading(messages[0], { id: "scan-progress" });
    try {
      const report = await analyzeDomain(d, pages, { signal: ctrl.signal });
      toast.dismiss(t);
      clearInterval(stageTimer);
      toast.success(`Report ready for ${report.domain?.domain || d}`, { duration: 2500 });
      sessionStorage.setItem(`report:${report.id}`, JSON.stringify(report));
      nav(`/report/${report.id}`);
    } catch (err) {
      toast.dismiss(t);
      clearInterval(stageTimer);
      if (err?.name !== "Canceled") {
        toast.error(err?.response?.data?.detail || err?.message || "Analysis failed");
      }
    } finally {
      setLoading(false);
      setAnalyzeAbort(null);
    }
  }

  return (
    <>
      <TopNav />
      <main className="px-6 lg:px-14 pb-24 max-w-7xl mx-auto">
        {/* Hero */}
        <section className="pt-10 lg:pt-20 flex flex-col lg:flex-row gap-10 lg:gap-20 items-start">
          <div className="flex-1 fade-in">
            <span className="chip chip-lav mb-6" data-testid="hero-chip">
              <i className="fa-solid fa-sparkles text-[11px]"></i>
              New · AI-powered audits
            </span>
            <h1 className="font-display text-4xl sm:text-5xl lg:text-6xl font-semibold text-[#2a2440] leading-[1.05]">
              Audit any website<br />
              in <em className="italic text-[#8b7fd3]">one soft</em> breath.
            </h1>
            <p className="mt-6 text-base lg:text-lg text-[#5c5577] max-w-xl leading-relaxed">
              Aryxton Labs is a pastel-powered website intelligence suite — SEO, security, performance,
              WHOIS and AI commentary. All in one glass dashboard. No account required.
            </p>

            <form onSubmit={onAnalyze} className="mt-9 glass p-3 flex flex-col sm:flex-row gap-3 max-w-2xl" data-testid="analyze-form" aria-label="Website analyse form">
              <label htmlFor="domain-input" className="sr-only">Website domain</label>
              <div className="flex-1 relative">
                <i className="fa-solid fa-link absolute left-5 top-1/2 -translate-y-1/2 text-[#8a84a3] pointer-events-none"></i>
                <input
                  id="domain-input"
                  type="text"
                  inputMode="url"
                  autoComplete="off"
                  autoCorrect="off"
                  autoCapitalize="off"
                  spellCheck={false}
                  className="input-glass flex-1 bg-transparent border-0 focus:shadow-none pl-11 !pr-4"
                  placeholder="example.com or https://example.com"
                  value={domain}
                  onChange={(e) => { setDomain(e.target.value); validateDomain(e.target.value); }}
                  disabled={loading}
                  data-testid="domain-input"
                  aria-invalid={!!fieldError}
                  aria-describedby={fieldError ? "domain-error" : undefined}
                />
              </div>
              <label htmlFor="pages-select" className="sr-only">Pages to crawl</label>
              <select
                id="pages-select"
                className="input-glass sm:w-36 bg-transparent border-0 focus:shadow-none"
                value={pages}
                onChange={(e) => setPages(Number(e.target.value))}
                disabled={loading}
                data-testid="max-pages-select"
              >
                {[
                  [3, "3 pages"],
                  [5, "5 pages"],
                  [8, "8 pages"],
                  [12, "12 pages"],
                  [20, "20 pages"],
                ].map(([n, label]) => <option key={n} value={n}>{label}</option>)}
              </select>
              <button type="submit" className="btn-primary justify-center min-w-[140px]" disabled={loading} data-testid="analyze-btn" aria-busy={loading}>
                {loading ? (
                  <>
                    <span className="flex gap-1.5" aria-hidden="true"><span className="pulse-dot"></span><span className="pulse-dot"></span><span className="pulse-dot"></span></span>
                    Scanning
                    {analyzeAbort && (
                      <span
                        role="button"
                        tabIndex={0}
                        className="ml-2 !p-1 !rounded-full hover:bg-black/10"
                        onClick={(e) => { e.preventDefault(); analyzeAbort.abort(); }}
                        aria-label="Cancel scan"
                      >
                        <i className="fa-solid fa-xmark text-xs"></i>
                      </span>
                    )}
                  </>
                ) : (
                  <>
                    <i className="fa-solid fa-wand-sparkles"></i>
                    Analyse
                  </>
                )}
              </button>
            </form>
            {fieldError && (
              <p id="domain-error" className="mt-3 text-sm text-[#8a2c54] flex items-center gap-2" role="alert">
                <i className="fa-solid fa-circle-exclamation"></i>{fieldError}
              </p>
            )}

            <div className="mt-5 flex flex-wrap items-center gap-2 text-xs text-[#8a84a3]">
              <span>Try:</span>
              {["github.com", "stripe.com", "notion.so", "example.com"].map((d) => (
                <button
                  key={d}
                  className="chip hover:!bg-white/75 transition-colors"
                  onClick={() => { setDomain(d); validateDomain(d); }}
                  disabled={loading}
                  type="button"
                  data-testid={`try-${d}`}
                >
                  {d}
                </button>
              ))}
            </div>
          </div>

          <div className="flex-1 w-full lg:max-w-md fade-in">
            <div className="glass p-6 space-y-4">
              <div className="flex items-center gap-3">
                <div className="grade-pill grade-Aplus text-2xl !w-14 !h-14">A+</div>
                <div>
                  <div className="font-display text-lg text-[#2a2440]">Optimal Security</div>
                  <div className="text-xs text-[#8a84a3]">example.com · 94/100</div>
                </div>
              </div>
              <div className="grid grid-cols-3 gap-2 text-center">
                {[
                  { l: "Pages", v: "12" },
                  { l: "Issues", v: "4" },
                  { l: "Avg LCP", v: "1.8s" },
                ].map((m) => (
                  <div key={m.l} className="glass-soft p-3">
                    <div className="font-display text-xl text-[#4a3b7a]">{m.v}</div>
                    <div className="text-[11px] uppercase tracking-wider text-[#8a84a3]">{m.l}</div>
                  </div>
                ))}
              </div>
              <div className="space-y-2">
                {[
                  { k: "SSL Certificate", v: "Valid · TLSv1.3", tint: "chip-mint" },
                  { k: "Content-Security-Policy", v: "Missing", tint: "chip-peach" },
                  { k: "robots.txt", v: "Found", tint: "chip-mint" },
                ].map((row) => (
                  <div key={row.k} className="flex items-center justify-between text-sm py-1">
                    <span className="text-[#5c5577]">{row.k}</span>
                    <span className={`chip ${row.tint}`}>{row.v}</span>
                  </div>
                ))}
              </div>
            </div>
            <p className="text-xs text-[#8a84a3] mt-3 text-center italic">a preview of what your report looks like</p>
          </div>
        </section>

        {/* Features */}
        <section className="mt-24 lg:mt-32">
          <div className="mb-10 max-w-2xl">
            <span className="chip chip-mint mb-3">What you get</span>
            <h2 className="font-display text-3xl lg:text-4xl text-[#2a2440]">A full-spectrum audit, served quietly.</h2>
          </div>
          <div className="grid md:grid-cols-2 lg:grid-cols-3 gap-5 stagger">
            {FEATURES.map((f, i) => (
              <div key={i} className="glass p-6 hover:translate-y-[-4px] transition-transform duration-300" data-testid={`feature-${i}`}>
                <span className={`chip ${f.tint} mb-4`}>
                  <i className={f.icon}></i>
                  {f.title}
                </span>
                <p className="text-[#5c5577] text-sm leading-relaxed">{f.desc}</p>
              </div>
            ))}
          </div>
        </section>

        {/* How it works */}
        <section className="mt-24 lg:mt-32">
          <div className="mb-10 max-w-2xl">
            <span className="chip chip-peach mb-3">How Aryxton Labs works</span>
            <h2 className="font-display text-3xl lg:text-4xl text-[#2a2440]">Three gentle steps.</h2>
          </div>
          <div className="grid md:grid-cols-3 gap-5 stagger">
            {[
              { n: "01", t: "Enter a domain", d: "No sign-up, no credit card. Just drop a URL and pick how deep to crawl." },
              { n: "02", t: "We scan quietly", d: "WHOIS, DNS, SEO crawl, OWASP header check, SSL inspection — all server-side." },
              { n: "03", t: "Review & export", d: "Glass dashboard, AI commentary, and a tidy Excel export whenever you want it." },
            ].map((s, i) => (
              <div key={i} className="glass p-6">
                <div className="font-display text-5xl text-[#c8b6ff] mb-3">{s.n}</div>
                <div className="font-display text-xl text-[#2a2440] mb-2">{s.t}</div>
                <p className="text-sm text-[#5c5577] leading-relaxed">{s.d}</p>
              </div>
            ))}
          </div>
        </section>

        {/* Trust / Stats */}
        <section className="mt-24 lg:mt-32">
          <div className="glass p-8 flex flex-col md:flex-row items-center justify-between gap-6 text-center md:text-left">
            <div className="max-w-md">
              <div className="font-display text-2xl text-[#2a2440]">Trusted by engineers. Loved by teams.</div>
              <p className="text-sm text-[#5c5577] mt-2">Aryxton Labsperforms hundreds of checks across SEO, TLS, OWASP headers and malware signals — with an AI copilot that actually suggests fixes.</p>
            </div>
            <div className="grid grid-cols-3 gap-6 md:gap-10 md:pr-4">
              {[
                { k: "200+", v: "Checks per scan" },
                { k: "A+ → F", v: "Security grades" },
                { k: "Open", v: "Source & API" },
              ].map((s, i) => (
                <div key={i}>
                  <div className="font-display text-2xl text-[#4a3b7a] tabular-nums">{s.k}</div>
                  <div className="text-[11px] uppercase tracking-[0.18em] text-[#8a84a3] mt-0.5">{s.v}</div>
                </div>
              ))}
            </div>
          </div>
        </section>

<footer className="mt-16 text-center text-xs text-[#8a84a3] space-y-2">
  <p>Built with FastAPI · React · Vite · MongoDB · OpenRouter</p>
  <p className="opacity-70">
    © {new Date().getFullYear()} Aryxton Labs Website Analyser · Pastel Intelligence Suite · by Arya Tiwari
  </p>
</footer>

      </main>
    </>
  );
}
